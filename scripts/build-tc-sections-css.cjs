/**
 * Generates app/styles/04-components/tc-sections.scss from the APPROVED design
 * (../design/final.html <style>) so the home components are a 1:1 copy.
 * Every selector is scoped under `.tc-s` (the wrapper every section component renders),
 * so the design's generic class names (.sec, .wrap, .btn…) never leak into the theme.
 * Re-run after the design changes:  node scripts/build-tc-sections-css.cjs
 */
const fs = require('fs');
const path = require('path');
const postcss = require('postcss');

const html = fs.readFileSync(path.join(__dirname, '../../design/final.html'), 'utf8');
const css = html.slice(html.indexOf('<style>') + 7, html.indexOf('</style>'));
const root = postcss.parse(css);
const S = '.tc-s';

root.walkRules(rule => {
  if (rule.parent.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.map(sel => {
    sel = sel.trim();
    if (sel === ':root' || sel === 'body') return S;
    if (sel === 'html') return S;
    if (sel === '*') return `${S}, ${S} *`;
    if (/^(html|body)\b/.test(sel)) return sel.replace(/^(html|body)/, S);
    return `${S} ${sel}`;
  });
});
// html{scroll-behavior} and body{overflow-x} are page-level — drop them inside a section
root.walkDecls(d => { if (/^(scroll-behavior|overflow-x)$/.test(d.prop) && d.parent.selector === S) d.remove(); });
// keyframes get a prefix so they can't clash with the theme's
const frames = new Set();
root.walkAtRules(/keyframes/i, at => { frames.add(at.params); at.params = 'tc-' + at.params; });
root.walkDecls(/^animation(-name)?$/, d => {
  d.value = d.value.split(/(\s+|,)/).map(w => (frames.has(w) ? 'tc-' + w : w)).join('');
});

// The base theme styles some elements globally (Tailwind preflight/forms + theme files) in ways
// the static design never had. Put them back to the browser defaults the design was drawn on —
// BEFORE the design rules, so every design rule still wins.
const RESET = [
  `${S} { display: block; }`,
  `${S} .btn { flex: 0 0 auto; line-height: inherit; font-weight: 600; }`, // theme: .btn { flex: 1; line-height: 1.25rem; bold } squashed buttons in column layouts
  `${S} button { line-height: normal; }`, // preflight makes buttons inherit the 1.7 body line-height
  `${S} h1, ${S} h2, ${S} h3, ${S} h4, ${S} h5, ${S} h6 { line-height: inherit; font-weight: 700; }`, // theme: h2/h3 fixed line-heights, inherit weight
  `${S} small { font-size: smaller; }`,
  `${S} select { appearance: auto; -webkit-appearance: menulist; background-image: none; padding-inline-end: 0; }`, // forms plugin arrow
  `${S} b, ${S} strong { font-weight: 700; }`,
].join('\n');

// Dark-mode ready: the design's light surfaces and dark bands become tokens with the design's
// own value as fallback, so the light look is unchanged and tc-dark.scss can swap them.
// white and the near-white creams: every channel ≥ 0xEE
const LIGHT_BG = { test: c => { const h = c.length === 4 ? c.slice(1).split('').map(x => x + x).join('') : c.slice(1); return [0, 2, 4].every(i => parseInt(h.slice(i, i + 2), 16) >= 0xee); } };
root.walkDecls(/^background(-color)?$/, d => {
  d.value = d.value
    .replace(/#[0-9a-f]{3,6}\b/gi, c => (LIGHT_BG.test(c) ? `var(--tc-card,${c})` : c))
    .replace(/var\(--(ink|dark|char)\)/g, 'var(--tc-band-$1,var(--$1))');
});
root.walkDecls(/^border(-[a-z]+)?(-color)?$/, d => {
  d.value = d.value.replace(/#(?:fff|ffffff)\b/gi, 'var(--tc-card,#fff)');
});
// dark text written as a literal (not var(--ink)) follows the text token too
root.walkDecls('color', d => {
  const v = d.value.trim();
  if (/^#(?:1d2023|2f3337|161819|222|111|000)$/i.test(v)) d.value = `var(--tc-text,${v})`;
  else if (/^#4d3800$/i.test(v)) d.value = 'var(--tc-gold-ink,#4d3800)'; // dark gold text on the soft-gold chips
});

const out = `// GENERATED by scripts/build-tc-sections-css.cjs from design/final.html — do not edit by hand.\n// Scoped under .tc-s (the wrapper of every "Tires Store" section component).\n${RESET}\n` + root.toString() + '\n';
fs.writeFileSync(path.join(__dirname, '../app/styles/04-components/tc-sections.scss'), out);
console.log('rules:', root.nodes.length);
