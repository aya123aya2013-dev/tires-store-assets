/**
 * Regenerates the Tailwind-utilities block at the end of app/styles/critical.scss.
 *
 * Harvests every class token from the layout and home components (any of them can
 * be above the fold on some store), finds each token's rules in the built
 * stylesheet — every occurrence, each with its own media wrapper — and rewrites
 * everything below the GENERATED marker in mobile-first variant order.
 *
 * Usage: build the theme first, then `node scripts/generate-critical-utils.mjs`.
 */
import { existsSync, readFileSync, writeFileSync, readdirSync } from 'node:fs';

const dirs = [
  'app/components/layout',
  'app/components/home',
  // Engine-rendered home blocks (FeaturedProducts styles, Brands, …) can also
  // sit above the fold; absent in the published starter kit, hence the guard.
  '../theme-engine/src/components/home',
  '../theme-engine/src/components/layout',
].filter((d) => existsSync(d));
const files = [
  ...dirs.flatMap((d) => readdirSync(d).map((f) => `${d}/${f}`)),
  'app/routes/__root.tsx',
].filter((f) => /\.(tsx|ts)$/.test(f));

// Every token-shaped string in the sources is a candidate — no quote parsing,
// which a template literal with inner quotes defeats. "Has a rule in the built
// sheet" (below) is what decides whether a candidate is a real class.
const tokens = new Set(['rounded-md', 'rounded-full']); // the skeletons' Pulse classes
for (const f of files) {
  for (const m of readFileSync(f, 'utf8').matchAll(/[A-Za-z0-9_:./[\]()%#-]{2,}/g)) {
    tokens.add(m[0]);
  }
}
const skip =
  /^(site-|s-|home-|mobile-|swiper|slide-|header-|enhanced-|overlay-bg|app-inner|is-|has-|salla|sicon|merge|store-|http|window|use|data-|aria|testimonial|scroll-carousel|photos|banner-|full-banner|feature|brands|tabs|repeated|\/|\d|#|\.)/;
const cand = [...tokens].filter((t) => !skip.test(t) && t.length > 1).sort();

const cssFile = readdirSync('dist/client/assets').find((f) => /^app-.*\.css$/.test(f));
if (!cssFile) throw new Error('Build the theme first: no dist/client/assets/app-*.css');
const css = readFileSync(`dist/client/assets/${cssFile}`, 'utf8');

// Top-level @media ranges, so every rule occurrence keeps its own wrapper.
const ranges = [];
for (const m of css.matchAll(/@media([^{]*)\{/g)) {
  let depth = 1;
  let i = m.index + m[0].length;
  while (depth && i < css.length) {
    if (css[i] === '{') depth += 1;
    else if (css[i] === '}') depth -= 1;
    i += 1;
  }
  ranges.push([m.index + m[0].length, i - 1, m[1].trim()]);
}
const condAt = (pos) => ranges.find(([a, b]) => pos >= a && pos < b)?.[2] ?? null;

const rank = (sel) => {
  const order = ['xs', 'sm', 'md', 'lg', 'xl', '2xl'];
  const bare = sel.replace(/^\./, '');
  const i = order.findIndex((v) => bare.startsWith(`${v}\\:`));
  return i < 0 ? 0 : i + 1;
};

const out = [];
// A rule occurrence counts only when the token is the start of its full
// selector: preceded by nothing, "}" or "{" (block edges) or "," (a grouped
// selector, whose declarations are shared). A space or combinator before it
// means it is the tail of a descendant selector like ".banner:hover .banner__title",
// whose conditions must not be dropped.
const startsSelector = (css, idx) => idx === 0 || '}{,'.includes(css[idx - 1]);
for (const t of cand) {
  const sel =
    '.' +
    t
      .replace(/:/g, '\\:')
      .replace(/\//g, '\\/')
      .replace(/\./g, '\\.')
      .replace(/([[\]()])/g, '\\$1');
  const needle = `${sel}{`;
  const seen = new Set();
  for (let i = css.indexOf(needle); i >= 0; i = css.indexOf(needle, i + 1)) {
    if (!startsSelector(css, i)) continue;
    const end = css.indexOf('}', i + needle.length);
    if (end < 0) continue;
    const body = css.slice(i + needle.length, end);
    const cond = condAt(i);
    const key = `${cond}|${body}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const rule = `${sel} {\n  ${body}\n}`;
    out.push({
      rank: rank(sel),
      sel,
      text: cond ? `@media ${cond} {\n  ${rule.replace(/\n/g, '\n  ')}\n}` : rule,
    });
  }
}
out.sort((a, b) => a.rank - b.rank || a.sel.localeCompare(b.sel));

const marker = '/* GENERATED by scripts/generate-critical-utils.mjs';
const critical = readFileSync('app/styles/critical.scss', 'utf8');
const at = critical.indexOf(marker);
if (at < 0) throw new Error('GENERATED marker not found in critical.scss');
const head = `${marker} — do not edit below by hand.
   Tailwind utilities used by the layout and home components (any can be above
   the fold on some store), copied from the built sheet with every occurrence's
   own media wrapper, in mobile-first variant order. Rebuild the theme, then
   rerun the script, whenever those components' class lists change. */
`;
writeFileSync(
  'app/styles/critical.scss',
  critical.slice(0, at) + head + out.map((o) => o.text).join('\n\n') + '\n'
);
console.log(`${out.length} rules for ${cand.length} tokens from ${files.length} files`);
